for (const locale of supportedLocales) {
  Object.assign(translations[locale], reviewFixTranslations[locale]);
}

export function t(locale: Locale, key: string, vars?: Record<string, string>) {
  const dict = translations[locale] ?? translations[defaultLocale];
  let value = dict[key] ?? translations[defaultLocale][key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      value = value.replace(new RegExp(`\\{${k}\\}`, "g"), v);
    });
  }
  return value;
}

// Defensive fallback for any stray global usage.
export const fallbackTranslate = (key: string, vars?: Record<string, string>) =>
  t(defaultLocale, key, vars);

if (typeof globalThis !== "undefined") {
  const g = globalThis as typeof globalThis & { translate?: typeof fallbackTranslate };
  if (!g.translate) {
    g.translate = fallbackTranslate;
  }
}
