// Helpers — PDF/print + .txt download
// ---------------------------------------------------------------------------

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function openPrintablePdf(doc: DocItem) {
  const win = window.open("", "_blank", "width=820,height=1000");
  if (!win) return;
  const owner = doc.owner ? `${doc.owner}` : "—";
  const statusLabel = doc.status ?? "—";
  const updated = doc.updatedAt ?? new Date().toISOString().slice(0, 10);

  win.document.write(`<!DOCTYPE html>
<html lang="uz">
  <head>
    <meta charset="utf-8" />
    <title>${escapeHtml(doc.title)}</title>
    <style>
      @page { margin: 24mm 20mm; }
      * { box-sizing: border-box; }
      body {
        font-family: 'Helvetica Neue', Arial, 'Noto Sans', sans-serif;
        color: #0f172a;
        margin: 0;
        padding: 32px 40px;
        line-height: 1.6;
      }
      .brand {
        font-size: 11px;
        text-transform: uppercase;
        letter-spacing: 0.08em;
        color: #4f46e5;
        font-weight: 600;
      }
      h1 {
        font-size: 24px;
        margin: 8px 0 16px;
        color: #0f172a;
      }
      .meta {
        display: flex;
        flex-wrap: wrap;
        gap: 16px;
        font-size: 12px;
        color: #475569;
        padding: 12px 0;
        border-top: 1px solid #e2e8f0;
        border-bottom: 1px solid #e2e8f0;
        margin-bottom: 24px;
      }
      .meta b { color: #0f172a; font-weight: 600; }
      .content {
        white-space: pre-wrap;
        font-size: 14px;
        color: #1e293b;
      }
      .footer {
        margin-top: 48px;
        padding-top: 16px;
        border-top: 1px solid #e2e8f0;
        font-size: 10px;
        color: #94a3b8;
        text-align: center;
      }
      @media print {
        body { padding: 0; }
        .no-print { display: none; }
      }
    </style>
  </head>
  <body>
    <div class="brand">AI Business Concierge — Hujjat</div>
    <h1>${escapeHtml(doc.title)}</h1>
    <div class="meta">
      <span><b>Mas'ul:</b> ${escapeHtml(owner)}</span>
      <span><b>Status:</b> ${escapeHtml(statusLabel)}</span>
      <span><b>Yangilandi:</b> ${escapeHtml(updated)}</span>
    </div>
    <div class="content">${escapeHtml(doc.content ?? "")}</div>
    <div class="footer">
      Generated by AI Business Concierge · ${new Date().toLocaleString()}
    </div>
  </body>
</html>`);
  win.document.close();
  win.setTimeout(() => {
    win.focus();
    win.print();
  }, 300);
}

function downloadAsTxt(doc: DocItem) {
  const lines = [
    doc.title,
    "=".repeat(Math.min(doc.title.length, 60)),
    "",
    `Mas'ul: ${doc.owner ?? "—"}`,
    `Status: ${doc.status ?? "—"}`,
    `Yangilandi: ${doc.updatedAt ?? new Date().toISOString().slice(0, 10)}`,
    "",
    "---",
    "",
    doc.content ?? "",
  ];
  const blob = new Blob([lines.join("\n")], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = window.document.createElement("a");
  a.href = url;
  a.download = `${doc.title.replace(/[^\wÀ-￿.-]+/g, "_")}.txt`;
  window.document.body.appendChild(a);
  a.click();
  window.document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

